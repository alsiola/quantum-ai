"""Phase 3c (issue #8): the memory benchmark suite, its literature checks and sanity runs.

Part 1 describes every task in ``[suite.tasks]`` exactly (optimum at the data
length, entropy rate, causal states, C_mu, C_q, quantum dimension) and checks
every recorded literature number (``qmem.benchmarks.LITERATURE``). Part 2
trains architecture A with the Phase 2 recipe on the ``[sanity.*]`` tasks and
measures, on the test split: the gap to the oracle, NLL and accuracy at the
recall positions (delayed recall), the stationary memory entropy (vs C_q),
the retention curve, and reference-qubit purification. Writes

* ``results/phase3c/<timestamp>/``: run records (``runs/<group>/seed<k>.json``
  and ``.pt``), ``suite.json``, ``analyses.json`` (raw, gitignored);
* ``<summary_dir>/``: ``suite.md``, ``sanity.md``, ``sanity.csv``,
  ``summary.json`` and plots (committed).

``--from-run <dir>`` reuses saved records and trains only missing runs;
``--suite-only`` skips part 2.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import time
import tomllib
from pathlib import Path
from typing import Any

import torch

from qmem.benchmarks import describe_benchmark, literature_checks, noise_profile, recall_metrics
from qmem.diagnostics import memory_report_for_model, prediction_retention
from qmem.experiment import RunSpec, aggregate, build_splits, load_model, mean_se, run_many
from qmem.records import REPO_ROOT, new_run_dir, run_metadata, save_json
from qmem.tasks import make_task

DEFAULT_CONFIG = Path(__file__).parent / "configs" / "phase3c.toml"
LN2 = math.log(2)


def fmt(x: Any, nd: int = 4) -> str:
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "n/a"
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


# -- part 1: the suite ------------------------------------------------------------
def describe_suite(cfg: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    length = cfg["data"]["length"]
    for name, spec in cfg["suite"]["tasks"].items():
        t0 = time.perf_counter()
        task = make_task({**spec, "name": name})
        row = describe_benchmark(task, length, mc_seed=cfg["suite"]["monte_carlo_seed"])
        row["spec"] = spec
        row["seconds"] = time.perf_counter() - t0
        rows.append(row)
        print(f"  {name:<26s} {row['seconds']:.1f}s")
    return rows


def suite_markdown(
    rows: list[dict[str, Any]], checks: list[dict[str, Any]], meta, noise: list[dict[str, Any]]
) -> str:
    length = rows[0]["length"] if rows else "?"
    lines = [
        "# Phase 3c benchmark suite",
        "",
        "Generated by `experiments/phase3c.py` from `experiments/configs/phase3c.toml`"
        f" (commit `{(meta['git_commit'] or '?')[:7]}`, dirty: {meta['git_dirty']}).",
        "Definitions, assumptions and citations:",
        "[`docs/benchmarks.md`](../../../docs/benchmarks.md).",
        "",
        f"## Exact optima (bits per symbol; sequences of length {length})",
        "",
        "`H/T` is the exact optimum `H(Y_1..Y_T)/T` from the source's start state; `h` the",
        "entropy rate. Memory columns are exact for unifilar sources: causal states,",
        "`C_mu`, and the phaseless quantum causal states' entropy `C_q` and dimension",
        "`dim_q` (Binder et al. 2018 construction).",
        "",
        "| task | alphabet (emitted) | generator | H/T | h | causal states | C_mu | C_q | dim_q |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        m = r["memory"]
        opt = r["optimal_nll_nats"]
        rate = r["entropy_rate_nats"]
        if rate is None:
            mc = r["entropy_rate_mc"]
            rate_s = f"{mc['nats'] / LN2:.4f} ± {mc['se'] / LN2:.4f} (MC)"
        else:
            rate_s = f"{rate / LN2:.4f}"
        dim_q = m.get("quantum_dim")
        if "qubit_model" in m:
            dim_q = f"{dim_q} (2 with phases)"
        lines.append(
            f"| {r['name']} | {r['n_symbols']} ({r['n_symbols_emitted']}) | {r['generator']} | "
            f"{fmt(opt / LN2) if opt is not None else 'not enumerable'} | {rate_s} | "
            f"{fmt(m.get('n_causal_states'))} | {fmt(m.get('c_mu_bits'))} | "
            f"{fmt(m.get('cq_bits'))} | {fmt(dim_q)} |"
        )
    lines += [
        "",
        "## Literature numbers",
        "",
        "Each number taken from a paper, against our value computed from the process",
        "definition. `figure` entries were read off a plot; `finite-sample` entries are",
        "the papers' empirical DA of the true model, with its SD as the tolerance.",
        "",
        "| check | source | quantity | reported | ours | tolerance | agrees |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in checks:
        rep = c["reported"]
        bound = "upper bound" in c["how"]
        lines.append(
            f"| {c['key']} | {c['source']} | {c['quantity']} | "
            f"{'< ' if bound else ''}{rep:.4g} | {c['ours']:.4g} | "
            f"{'n/a' if bound else f'{c["tol"]:.2g}'} | {'yes' if c['agrees'] else '**no**'} |"
        )
    n_ok = sum(c["agrees"] for c in checks)
    lines += ["", f"{n_ok} of {len(checks)} literature numbers reproduced.", ""]
    if noise:
        dims = sorted(noise[0]["eta_floor"])
        lines += [
            "## Retention probes with noise eps",
            "",
            "Delayed recall: the recall symbol is wrong with probability eps. Parity: the output",
            "is flipped with probability eps. Mixed timescales: the data bit breaks its regime's",
            "rule with probability eps. eps = 0 is the default. `eta_floor(d)` is the least",
            "operational strength (`qmem.metrics.strength_lower_bound`) with which any instrument",
            "on a `d`-dimensional memory can reproduce the source exactly. It is exact here,",
            "taken over the causal states. Optima in bits per symbol, length "
            f"{noise[0]['length']}.",
            "",
            "| probe | eps | H/T | h | recall-position optimum (NLL bits / acc) | "
            "min / max emission prob | " + " | ".join(f"eta_floor(d={d})" for d in dims) + " |",
            "|---|---|---|---|---|---|" + "---|" * len(dims),
        ]
        for r in noise:
            rec = (
                f"{r['recall_optimal_nll_nats'] / LN2:.4f} / {r['recall_optimal_accuracy']:.2f}"
                if "recall_optimal_nll_nats" in r
                else "n/a"
            )
            floors = " | ".join(f"{r['eta_floor'][d]:.4f}" for d in dims)
            lines.append(
                f"| {r['probe']} | {r['eps']:g} | {r['optimal_nll_nats'] / LN2:.4f} | "
                f"{r['entropy_rate_nats'] / LN2:.4f} | {rec} | "
                f"{r['min_emission_prob']:.4f} / {r['max_emission_prob']:.4f} | {floors} |"
            )
        lines.append("")
    return "\n".join(lines)


# -- part 2: sanity runs ----------------------------------------------------------
def sanity_specs(cfg: dict[str, Any]) -> list[RunSpec]:
    specs = []
    for name, t in cfg.get("sanity", {}).items():
        for nm in t["n_memory"]:
            model = {**cfg["model"], "n_memory": nm, "n_output": t["n_output"]}
            for seed in cfg["experiment"]["seeds"]:
                specs.append(
                    RunSpec(
                        group=f"sanity/{name}/m{nm}",
                        task={**t["spec"], "name": name},
                        data=cfg["data"],
                        model=model,
                        train=cfg["train"],
                        seed=seed,
                        labels={"task": name, "n_memory": nm},
                    )
                )
    return specs


def load_records(run_dir: Path) -> list[dict[str, Any]]:
    records = []
    for path in sorted((run_dir / "runs").rglob("seed*.json")):
        rec = json.loads(path.read_text())
        pt = path.with_suffix(".pt")
        if pt.exists():
            rec["state_dict"] = torch.load(pt)
        records.append(rec)
    return records


def analyse_run(rec: dict[str, Any], cfg: dict[str, Any]) -> dict[str, Any]:
    """Recall metrics and memory diagnostics of one trained run on its test split."""
    out: dict[str, Any] = {"group": rec["group"], "seed": rec["seed"], "status": rec["status"]}
    if "state_dict" not in rec:
        return out
    a = cfg["analysis"]
    spec = rec["meta"]["config"]["task"]
    task = make_task(spec)
    test = build_splits(task, rec["meta"]["config"]["data"]).test
    model = load_model(rec)
    if spec["kind"] == "delayed_recall":
        out["recall"] = recall_metrics(model, task, test)
    report = memory_report_for_model(
        model,
        test,
        a["retention_lags"],
        burn_in=a["burn_in"],
        purification_seed=a["purification_seed"],
        n_reference=a["n_reference"],
    )
    for key in ("purification_teacher_forced", "purification_generated"):
        report[key].pop("entropy_se_bits", None)
    out.update(report)
    out["source_prediction_retention"] = prediction_retention(
        task.predictive(test), test, a["retention_lags"], a["burn_in"]
    )
    return out


def summarise_groups(
    rows: list[dict[str, Any]], analyses: list[dict[str, Any]], suite_by_name: dict[str, Any]
) -> list[dict[str, Any]]:
    by_group: dict[str, list[dict[str, Any]]] = {}
    for an in analyses:
        by_group.setdefault(an["group"], []).append(an)
    out = []
    for row in rows:
        ans = [a for a in by_group.get(row["group"], []) if "stationary_memory" in a]
        task_name = row["labels"]["task"]
        mem = suite_by_name.get(task_name, {}).get("memory", {})
        s: dict[str, Any] = {
            "group": row["group"],
            "task": task_name,
            "n_memory": row["labels"]["n_memory"],
            "n_runs": row["n_runs"],
            "n_success": row["n_success"],
            "gap_mean": row["gap_mean"],
            "gap_se": row["gap_se"],
            "gap_median": row["gap_median"],
            "gap_best": row["gap_best"],
            "oracle_nll_nats": row["oracle_nll_nats"],
            "optimal_nll_nats": row["optimal_nll_nats"],
            "test_nll_mean": row["test_nll_mean"],
            "c_mu_bits": mem.get("c_mu_bits"),
            "cq_bits": mem.get("cq_bits"),
            "n_causal_states": mem.get("n_causal_states"),
        }
        ent = [a["stationary_memory"]["entropy_bits"] for a in ans]
        s["memory_entropy_mean"], s["memory_entropy_se"] = mean_se(ent)
        lags = sorted({int(k) for a in ans for k in a["retention"]})
        s["holevo_by_lag"] = {
            lag: mean_se([a["retention"][lag]["holevo_bits"] for a in ans])[0] for lag in lags
        }
        s["prediction_mi_by_lag"] = {
            lag: mean_se([a["retention"][lag]["prediction_mi_bits"] for a in ans])[0]
            for lag in lags
        }
        if ans:
            s["source_prediction_mi_by_lag"] = {
                int(k): v for k, v in ans[0]["source_prediction_retention"].items()
            }
        for mode in ("teacher_forced", "generated"):
            pur = [a[f"purification_{mode}"] for a in ans]
            s[f"purified_fraction_{mode}"] = mean_se([p["fraction_purified"] for p in pur])[0]
            meds = [p["purification_time_median"] for p in pur]
            meds = [m for m in meds if math.isfinite(m)]
            s[f"purification_median_{mode}"] = mean_se(meds)[0]
        rec = [a["recall"] for a in ans if "recall" in a]
        if rec:
            s["recall_nll_mean"], s["recall_nll_se"] = mean_se([r["recall_nll_nats"] for r in rec])
            s["recall_acc_mean"], s["recall_acc_se"] = mean_se([r["recall_accuracy"] for r in rec])
            s["recall_acc_best"] = max(r["recall_accuracy"] for r in rec)
            s["other_nll_mean"] = mean_se([r["other_nll_nats"] for r in rec])[0]
        out.append(s)
    return out


def sanity_markdown(groups: list[dict[str, Any]], cfg: dict[str, Any], meta, wall: float) -> str:
    seeds = cfg["experiment"]["seeds"]
    lines = [
        "# Phase 3c sanity runs: architecture A on the benchmark suite",
        "",
        "Generated by `experiments/phase3c.py` from `experiments/configs/phase3c.toml`"
        f" (commit `{(meta['git_commit'] or '?')[:7]}`, dirty: {meta['git_dirty']}).",
        f"Phase 2 recipe, {len(seeds)} model seeds per row, data seed {cfg['data']['seed']}, "
        f"{cfg['data']['n_train']}/{cfg['data']['n_val']}/{cfg['data']['n_test']} sequences "
        f"of length {cfg['data']['length']}. Wall time {wall / 60:.1f} min.",
        "",
        "## Test NLL (nats/symbol)",
        "",
        "Gap = model NLL - source NLL on the same test sequences (mean ± SE over seeds);"
        f" a run succeeds if its gap is below {cfg['experiment']['success_gap']}.",
        "",
        "| task | mem qubits | optimum H/T | oracle | model | gap mean ± SE | median | best | ok |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for g in groups:
        lines.append(
            f"| {g['task']} | {g['n_memory']} | {fmt(g['optimal_nll_nats'])} | "
            f"{fmt(g['oracle_nll_nats'])} | {fmt(g['test_nll_mean'])} | "
            f"{fmt(g['gap_mean'])} ± {fmt(g['gap_se'])} | {fmt(g['gap_median'])} | "
            f"{fmt(g['gap_best'])} | {g['n_success']}/{g['n_runs']} |"
        )
    rec = [g for g in groups if "recall_acc_mean" in g]
    if rec:
        lines += [
            "",
            "## Delayed recall: the recall positions",
            "",
            "The exact source has recall NLL 0 and accuracy 1; a model that does not hold the",
            f"cue scores ln 2 = {LN2:.4f} and 0.5. `other` = NLL on the remaining positions"
            f" (optimum ln 2).",
            "",
            "| task | mem qubits | causal states | recall NLL mean ± SE | recall acc mean ± SE "
            "| best acc | other NLL |",
            "|---|---|---|---|---|---|---|",
        ]
        for g in rec:
            lines.append(
                f"| {g['task']} | {g['n_memory']} | {fmt(g['n_causal_states'])} | "
                f"{fmt(g['recall_nll_mean'])} ± {fmt(g['recall_nll_se'])} | "
                f"{fmt(g['recall_acc_mean'], 3)} ± {fmt(g['recall_acc_se'], 3)} | "
                f"{fmt(g['recall_acc_best'], 3)} | {fmt(g['other_nll_mean'])} |"
            )
    lag_set = cfg["analysis"]["retention_lags"]
    lines += [
        "",
        "## Memory diagnostics (test split, means over seeds)",
        "",
        "`S(memory)`: von Neumann entropy (bits) of the time-averaged conditional memory,"
        " to compare with `C_q` (the source's quantum memory) and `C_mu`. Holevo(τ): the"
        " mutual information (bits) between the symbol τ steps back and the memory."
        " Purified: fraction of trajectories whose 1-qubit reference falls below 0.01 bits"
        " within the sequence (teacher-forced / self-generated), and the median time.",
        "",
        "| task | mem qubits | C_mu | C_q | S(memory) | "
        + " | ".join(f"Holevo({lag})" for lag in lag_set[:5])
        + " | purified TF / gen | median t TF / gen |",
        "|---|---|---|---|---|" + "---|" * min(5, len(lag_set)) + "---|---|",
    ]
    for g in groups:
        hol = " | ".join(fmt(g["holevo_by_lag"].get(lag), 3) for lag in lag_set[:5])
        lines.append(
            f"| {g['task']} | {g['n_memory']} | {fmt(g['c_mu_bits'], 3)} | {fmt(g['cq_bits'], 3)}"
            f" | {fmt(g['memory_entropy_mean'], 3)} ± {fmt(g['memory_entropy_se'], 3)} | {hol} | "
            f"{fmt(g['purified_fraction_teacher_forced'], 2)} / "
            f"{fmt(g['purified_fraction_generated'], 2)} | "
            f"{fmt(g['purification_median_teacher_forced'], 1)} / "
            f"{fmt(g['purification_median_generated'], 1)} |"
        )
    lines.append("")
    return "\n".join(lines)


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    flat = [{k: v for k, v in r.items() if not isinstance(v, dict)} for r in rows]
    keys = list(dict.fromkeys(k for r in flat for k in r))
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(flat)


def make_plots(summary_dir: Path, groups: list[dict[str, Any]]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    ax = axes[0]
    ax.set_prop_cycle(color=plt.cm.tab20.colors)
    for g in groups:
        lags = sorted(g["holevo_by_lag"])
        ax.plot(
            lags,
            [g["holevo_by_lag"][k] for k in lags],
            marker="o",
            ms=3,
            label=f"{g['task']} m{g['n_memory']}",
        )
    ax.set_xlabel("lag τ (symbols)")
    ax.set_ylabel("Holevo information past symbol ↔ memory (bits)")
    ax.set_yscale("symlog", linthresh=1e-3)
    ax.legend(fontsize=6, ncol=2)
    ax.set_title("Retention curves (architecture A, mean over seeds)")
    ax = axes[1]
    rec = [g for g in groups if "recall_acc_mean" in g]
    for m in sorted({g["n_memory"] for g in rec}):
        sub = [g for g in rec if g["n_memory"] == m]
        taus = [int(g["task"].split("tau")[1]) for g in sub]
        ax.errorbar(
            taus,
            [g["recall_acc_mean"] for g in sub],
            yerr=[g["recall_acc_se"] for g in sub],
            marker="o",
            capsize=3,
            label=f"{m} memory qubits (mean ± SE)",
        )
        ax.plot(
            taus,
            [g["recall_acc_best"] for g in sub],
            ls=":",
            marker="x",
            label=f"{m} memory qubits (best seed)",
        )
    ax.axhline(0.5, color="grey", lw=0.8, ls="--")
    ax.axhline(1.0, color="grey", lw=0.8)
    ax.set_xscale("log", base=2)
    ax.set_xlabel("delay τ")
    ax.set_ylabel("accuracy at the recall position")
    ax.set_ylim(0.4, 1.05)
    ax.legend(fontsize=7)
    ax.set_title("Delayed recall (optimum 1, memoryless 0.5)")
    fig.tight_layout()
    fig.savefig(summary_dir / "sanity.png", dpi=130)
    plt.close(fig)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--config", default=str(DEFAULT_CONFIG))
    p.add_argument("--workers", type=int, default=None, help="override [experiment].workers")
    p.add_argument("--from-run", default=None, help="reuse records in this results directory")
    p.add_argument("--suite-only", action="store_true", help="skip the training runs")
    args = p.parse_args()
    start = time.perf_counter()
    cfg = tomllib.loads(Path(args.config).read_text())
    exp = cfg["experiment"]
    summary_dir = REPO_ROOT / exp["summary_dir"]
    summary_dir.mkdir(parents=True, exist_ok=True)
    out = Path(args.from_run) if args.from_run else new_run_dir(exp["name"])
    meta = run_metadata(cfg)
    save_json(out / "config.json", {"meta": meta, "config_path": args.config})

    print("part 1: describing the suite ...")
    suite = describe_suite(cfg)
    checks = literature_checks()
    nz = cfg["suite"].get("noise")
    noise = noise_profile(nz["eps"], cfg["data"]["length"], nz["dims"]) if nz else []
    payload = {"meta": meta, "suite": suite, "literature": checks, "noise": noise}
    save_json(out / "suite.json", payload)
    save_json(summary_dir / "suite.json", payload)
    (summary_dir / "suite.md").write_text(suite_markdown(suite, checks, meta, noise))
    print(f"  literature: {sum(c['agrees'] for c in checks)}/{len(checks)} reproduced")
    if args.suite_only:
        return

    specs = sanity_specs(cfg)
    records = load_records(out) if args.from_run else []
    have = {(r["group"], r["seed"]) for r in records}
    missing = [s for s in specs if (s.group, s.seed) not in have]
    print(f"part 2: {len(missing)} runs to train ({len(records)} saved) -> {out}")
    records += run_many(missing, out, workers=args.workers or exp["workers"])
    order = {(s.group, s.seed): i for i, s in enumerate(specs)}
    records = sorted(
        (r for r in records if (r["group"], r["seed"]) in order),
        key=lambda r: order[(r["group"], r["seed"])],
    )
    print("analysing ...")
    analyses = [analyse_run(r, cfg) for r in records]
    rows = aggregate(records, exp["success_gap"])
    suite_by_name = {}
    for name, t in cfg["sanity"].items():
        task = make_task({**t["spec"], "name": name})
        suite_by_name[name] = describe_benchmark(task, cfg["data"]["length"])
    groups = summarise_groups(rows, analyses, suite_by_name)
    wall = time.perf_counter() - start
    save_json(out / "analyses.json", {"meta": meta, "analyses": analyses, "groups": groups})
    run_commits = sorted({r["meta"]["git_commit"] for r in records})
    save_json(
        summary_dir / "summary.json",
        {"meta": meta, "run_commits": run_commits, "aggregate": rows, "groups": groups},
    )
    write_csv(summary_dir / "sanity.csv", groups)
    (summary_dir / "sanity.md").write_text(sanity_markdown(groups, cfg, meta, wall))
    make_plots(summary_dir, groups)
    print((summary_dir / "sanity.md").read_text())
    print(f"wrote {summary_dir} and {out} ({wall / 60:.1f} min)")


if __name__ == "__main__":
    main()
