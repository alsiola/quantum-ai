"""Post-training analyses: sample statistics, Markov baselines, interventions, memory.

* ``ngram_distribution`` / ``tv_distance`` / ``run_lengths``: compare sequences
  generated by ``model.sample`` (the generation path) with the source.
* ``markov_baseline_nll``: the best order-``k`` count model on the same splits
  (add-``alpha`` smoothing, ``alpha`` chosen on validation). Positions with
  fewer than ``k`` predecessors use the longest available context.
* ``intervention_effects``: change one past symbol at lag ``l`` and measure how
  much ``p(next | prefix)`` moves (total variation), for the model and the
  exact source. Memory shows up as a nonzero effect at the lags the source
  depends on.
* ``memory_trajectories``: along teacher-forced test sequences, the purity and
  entropy of the conditional memory ``rho_t``, its trace distance to the
  outcome-averaged memory ``E^t(rho_0)``, and the NLL obtained when predicting
  from ``E^{t-1}(rho_0)`` instead (the outcome-discarded memory; a preview of
  ablation B, not the ablation itself).
* ``instrument_summary``: spectrum of the POVM effects and Kraus operators,
  to spot collapsed or degenerate instruments.
* ``curve_pathologies``: gradient spikes and plateaus in a training curve.
"""

from __future__ import annotations

import math
from collections import Counter
from typing import Any

import torch

from .data import all_sequences
from .linalg import REAL_DTYPE
from .model import QuantumMemoryModel
from .states import purity, von_neumann_entropy
from .tasks import HMMTask


# -- sample statistics -----------------------------------------------------------
def ngram_distribution(seqs: torch.Tensor, n: int, n_symbols: int) -> torch.Tensor:
    """Empirical distribution of the ``n``-grams in all windows, shape ``(Y**n,)``."""
    seqs = torch.as_tensor(seqs, dtype=torch.long)
    windows = seqs.unfold(1, n, 1).reshape(-1, n)
    powers = n_symbols ** torch.arange(n - 1, -1, -1)
    idx = (windows * powers).sum(-1)
    counts = torch.bincount(idx, minlength=n_symbols**n).to(REAL_DTYPE)
    return counts / counts.sum()


def tv_distance(p: torch.Tensor, q: torch.Tensor) -> float:
    return float(0.5 * (p - q).abs().sum())


def run_lengths(seqs: torch.Tensor, symbol: int = 1) -> Counter[int]:
    """Lengths of runs of ``symbol`` bounded by another symbol on both sides."""
    out: Counter[int] = Counter()
    for row in torch.as_tensor(seqs).tolist():
        run, opened = 0, False
        for y in row:
            if y == symbol:
                run += 1
            else:
                if opened and run > 0:
                    out[run] += 1
                opened, run = True, 0
    return out


def sample_statistics(
    model_samples: torch.Tensor,
    source_samples: torch.Tensor,
    reference_samples: torch.Tensor,
    n_symbols: int,
    max_n: int = 3,
) -> dict[str, Any]:
    """n-gram TV distance model-vs-source, against a source-vs-source noise floor."""
    out: dict[str, Any] = {"ngram_tv": {}, "ngram_tv_noise_floor": {}}
    for n in range(1, max_n + 1):
        src = ngram_distribution(source_samples, n, n_symbols)
        out["ngram_tv"][n] = tv_distance(ngram_distribution(model_samples, n, n_symbols), src)
        out["ngram_tv_noise_floor"][n] = tv_distance(
            ngram_distribution(reference_samples, n, n_symbols), src
        )
    if n_symbols == 2:
        for name, s in (("model", model_samples), ("source", source_samples)):
            runs = run_lengths(s, symbol=1)
            total = sum(runs.values())
            odd = sum(c for k, c in runs.items() if k % 2)
            out[f"runs_of_1_{name}"] = {str(k): runs[k] for k in sorted(runs)}
            out[f"odd_run_fraction_{name}"] = odd / total if total else math.nan
            out[f"n_runs_{name}"] = total
    return out


# -- order-k Markov baselines ---------------------------------------------------------
def _context_index(seqs: torch.Tensor, t: int, j: int, n_symbols: int) -> torch.Tensor:
    if j == 0:
        return torch.zeros(seqs.shape[0], dtype=torch.long)
    powers = n_symbols ** torch.arange(j - 1, -1, -1)
    return (seqs[:, t - j : t] * powers).sum(-1)


def _markov_counts(train: torch.Tensor, k: int, n_symbols: int) -> list[torch.Tensor]:
    """counts[j][context, y] for context length j = 0..k, pooled over positions t >= j."""
    counts = []
    for j in range(k + 1):
        c = torch.zeros(n_symbols**j, n_symbols, dtype=REAL_DTYPE)
        for t in range(j, train.shape[1]):
            ctx = _context_index(train, t, j, n_symbols)
            c.index_put_(
                (ctx, train[:, t]), torch.ones(train.shape[0], dtype=REAL_DTYPE), accumulate=True
            )
        counts.append(c)
    return counts


def _markov_nll(
    counts: list[torch.Tensor], seqs: torch.Tensor, k: int, n_symbols: int, alpha: float
) -> float:
    total = 0.0
    for t in range(seqs.shape[1]):
        j = min(t, k)
        c = counts[j]
        probs = (c + alpha) / (c + alpha).sum(-1, keepdim=True)
        ctx = _context_index(seqs, t, j, n_symbols)
        total += float(-torch.log(probs[ctx, seqs[:, t]]).sum())
    return total / seqs.numel()


def markov_baseline_nll(
    train: torch.Tensor,
    val: torch.Tensor,
    test: torch.Tensor,
    k: int,
    n_symbols: int,
    alphas: tuple[float, ...] = (0.01, 0.1, 0.5, 1.0),
) -> dict[str, float]:
    """Test NLL (nats/symbol) of the order-``k`` count model, ``alpha`` picked on val."""
    counts = _markov_counts(train, k, n_symbols)
    val_nll = {a: _markov_nll(counts, val, k, n_symbols, a) for a in alphas}
    best = min(val_nll, key=val_nll.__getitem__)
    return {
        "k": k,
        "alpha": best,
        "val_nll": val_nll[best],
        "test_nll": _markov_nll(counts, test, k, n_symbols, best),
    }


# -- interventions ------------------------------------------------------------------
@torch.no_grad()
def intervention_effects(
    model: QuantumMemoryModel,
    task: HMMTask,
    seqs: torch.Tensor,
    lags: list[int],
    prefix_len: int,
    seed: int,
) -> list[dict[str, Any]]:
    """Mean TV change of ``p(next | prefix)`` when the symbol at lag ``l`` is replaced.

    The replacement is a uniformly random *different* symbol (seeded). Prefixes
    made impossible under the source are excluded from both averages (their
    count is reported), so model and source are compared on the same rows.
    """
    gen = torch.Generator().manual_seed(seed)
    prefixes = torch.as_tensor(seqs, dtype=torch.long)[:, :prefix_len]
    y_dim = task.n_symbols
    base_m = model.predictive_probs(prefixes)[:, -1]
    base_s = task.predictive(prefixes)[:, -1]
    rows = []
    for lag in lags:
        alt = prefixes.clone()
        pos = prefix_len - lag
        shift = torch.randint(1, y_dim, (alt.shape[0],), generator=gen)
        alt[:, pos] = (alt[:, pos] + shift) % y_dim
        m = model.predictive_probs(alt)[:, -1]
        s = task.predictive(alt)[:, -1]
        valid = torch.isfinite(s).all(-1) & torch.isfinite(base_s).all(-1)
        tv_m = 0.5 * (m - base_m).abs().sum(-1)
        tv_s = 0.5 * (s - base_s).abs().sum(-1)
        rows.append(
            {
                "lag": lag,
                "model_tv": float(tv_m[valid].mean()),
                "model_tv_se": float(tv_m[valid].std() / math.sqrt(int(valid.sum()))),
                "source_tv": float(tv_s[valid].mean()),
                "n_valid": int(valid.sum()),
                "n_excluded": int((~valid).sum()),
            }
        )
    return rows


@torch.no_grad()
def context_table(
    model: QuantumMemoryModel, task: HMMTask, seqs: torch.Tensor, k: int
) -> list[dict[str, Any]]:
    """Mean ``p(next)`` grouped by the last ``k`` symbols, model vs source (``t >= k``)."""
    seqs = torch.as_tensor(seqs, dtype=torch.long)
    y_dim = task.n_symbols
    pm = model.predictive_probs(seqs)[:, :-1]
    ps = task.predictive(seqs)[:, :-1]
    rows = []
    for c, ctx in enumerate(all_sequences(y_dim, k).tolist()):
        sel_m, sel_s = [], []
        for t in range(k, seqs.shape[1]):
            mask = _context_index(seqs, t, k, y_dim) == c
            sel_m.append(pm[mask, t])
            sel_s.append(ps[mask, t])
        m, s = torch.cat(sel_m), torch.cat(sel_s)
        if len(m) == 0:
            continue
        rows.append(
            {
                "context": ctx,
                "count": len(m),
                "model_p": m.mean(0).tolist(),
                "source_p": s.mean(0).tolist(),
            }
        )
    return rows


@torch.no_grad()
def prefix_predictions(
    model: QuantumMemoryModel, task: HMMTask, prefixes: list[list[int]]
) -> list[dict[str, Any]]:
    """``p(next | prefix)`` for hand-picked prefixes, model vs source."""
    out = []
    for pre in prefixes:
        x = torch.tensor([pre], dtype=torch.long)
        if len(pre) == 0:
            x = torch.zeros(1, 0, dtype=torch.long)
        out.append(
            {
                "prefix": pre,
                "model_p": model.predictive_probs(x)[0, -1].tolist(),
                "source_p": task.predictive(x)[0, -1].tolist(),
            }
        )
    return out


# -- memory along trajectories ---------------------------------------------------------
def trace_distance(a: torch.Tensor, b: torch.Tensor) -> torch.Tensor:
    diff = a - b
    diff = (diff + diff.conj().transpose(-1, -2)) / 2
    return 0.5 * torch.linalg.eigvalsh(diff).abs().sum(-1)


@torch.no_grad()
def memory_trajectories(model: QuantumMemoryModel, seqs: torch.Tensor) -> dict[str, Any]:
    """Per-step means over sequences of memory diagnostics (``t = 0..T``).

    ``conditional_*``: purity and von Neumann entropy (bits) of ``rho_t``.
    ``unconditioned_*``: the same for ``E^t(rho_0)``.
    ``distance_to_unconditioned``: mean trace distance ``D(rho_t, E^t(rho_0))``.
    ``spread``: mean trace distance of ``rho_t`` to the across-sequence mean
    ``mean_b rho_t^(b)`` (how much the memory depends on the history).
    ``nll_conditioned`` / ``nll_unconditioned``: mean ``-log p(y_t)`` per step when
    predicting from ``rho_{t-1}`` vs from ``E^{t-1}(rho_0)``.
    """
    seqs = torch.as_tensor(seqs, dtype=torch.long)
    inst = model.instrument()
    memory = model.initial_memory(seqs.shape[0])
    unc = model.rho0
    keys = (
        "conditional_purity",
        "conditional_entropy",
        "unconditioned_purity",
        "unconditioned_entropy",
        "distance_to_unconditioned",
        "spread",
        "nll_conditioned",
        "nll_unconditioned",
    )
    out: dict[str, list[float]] = {k: [] for k in keys}

    def record(rho: torch.Tensor, rho_u: torch.Tensor) -> None:
        out["conditional_purity"].append(float(purity(rho).mean()))
        out["conditional_entropy"].append(float(von_neumann_entropy(rho).mean()))
        out["unconditioned_purity"].append(float(purity(rho_u)))
        out["unconditioned_entropy"].append(float(von_neumann_entropy(rho_u)))
        out["distance_to_unconditioned"].append(float(trace_distance(rho, rho_u).mean()))
        out["spread"].append(float(trace_distance(rho, rho.mean(0)).mean()))

    record(memory.rho, unc)
    for t in range(seqs.shape[1]):
        y = seqs[:, t]
        p_u = inst.probabilities(unc)[y]
        out["nll_unconditioned"].append(float(-torch.log(p_u).mean()))
        memory, logp = model.observe(inst, memory, y)
        out["nll_conditioned"].append(float(-logp.mean()))
        unc = inst.channel(unc)
        record(memory.rho, unc)
    return out


@torch.no_grad()
def instrument_summary(model: QuantumMemoryModel) -> dict[str, Any]:
    """Effect eigenvalues per outcome and Kraus singular values (collapse diagnostics).

    An effect with all eigenvalues near 0 (an outcome that never happens) or
    all near 1, or Kraus operators of rank 1 (the post-measurement memory
    forgets its input), signals a degenerate instrument.
    """
    inst = model.instrument()
    eff = torch.linalg.eigvalsh(inst.effects()).tolist()
    sv = torch.linalg.svdvals(inst.kraus).tolist()
    kraus = inst.kraus.reshape(-1, inst.dim, inst.dim)
    rank = [int((torch.linalg.svdvals(k) > 1e-6).sum()) for k in kraus]
    return {"effect_eigenvalues": eff, "kraus_singular_values": sv, "kraus_ranks": rank}


def curve_pathologies(curves: dict[str, list], spike_factor: float = 10.0) -> dict[str, Any]:
    """Gradient spikes (norm > ``spike_factor`` x running median of the last 20 steps),
    the largest gradient norm, clipped steps, and the longest validation plateau
    (consecutive evaluations improving the best by < 1e-3 nats/symbol)."""
    g = [x for x in curves.get("grad_norm", []) if math.isfinite(x)]
    spikes = 0
    for i in range(20, len(g)):
        window = sorted(g[i - 20 : i])
        if g[i] > spike_factor * window[10]:
            spikes += 1
    val = curves.get("val_nll", [])
    best, run, longest = math.inf, 0, 0
    for v in val:
        if v < best - 1e-3:
            best, run = v, 0
        else:
            run += 1
            longest = max(longest, run)
    every = (curves["eval_step"][1] - curves["eval_step"][0]) if len(val) > 1 else 0
    return {
        "grad_spikes": spikes,
        "grad_norm_max": max(g, default=math.nan),
        "grad_norm_median": sorted(g)[len(g) // 2] if g else math.nan,
        "clipped_steps": sum(bool(c) for c in curves.get("clipped", [])),
        "longest_plateau_steps": longest * every,
    }
